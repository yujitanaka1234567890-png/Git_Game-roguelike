// 初めて遊ぶ時（保存データがない時）は、最初に「説明を読むか」をたずねる（askFirstTime）。
// ページは短めに。←→ の代わりに「次へ／前へ」の選択肢でめくる（選択ウィンドウ dialog.js を使う）。
Game.tutorial = {
  pages: [
    {
      title: "遊び方 1/5：目的",
      lines: [
        "拠点の下の門（∩）からダンジョンへ出発する。",
        "一番下の階にいるボスを倒すと帰還のゲートが現れ、そこから帰ると「踏破」。新しいダンジョンが開く。",
        "途中で倒れると、その冒険で仲間になった子と持ち物を失う（拠点から連れてきた子は牧場に残る）。",
      ],
    },
    {
      title: "遊び方 2/5：操作",
      lines: [
        "矢印キー：移動。敵に向かって進むと攻撃。Shift＋矢印2つで斜め、Shift＋矢印1つでダッシュ。",
        "スペース：その場で1ターン待つ。I（または W）：持ち物。階段の上で ↓ を2回：次の階へ。",
        "自分が1回動くと、仲間と敵も1回動く（ターン制）。",
      ],
    },
    {
      title: "遊び方 3/5：仲間",
      lines: [
        "倒した敵は、ときどき心を開いて仲間になる（めずらしい種類ほどなりにくい）。",
        "生きて帰ると仲間は牧場へ。掲示板（掲）で次の冒険に連れて行く子を選べる。",
        "仲間はレベルが上がると進化する。交配小屋（♥）で2体から新しい仲間も生まれる。",
      ],
    },
    {
      title: "遊び方 4/5：精神力",
      lines: [
        "ダンジョンにいると精神力が少しずつ減る。同じ階に長居すると速く減る。",
        "減ってくると遠吠えやささやきが聞こえ、画面の下に警告が出る。0のまま3ターンたつとダンジョンに取り込まれる。",
        "階段を降りる・香や煙草などの道具で回復する。HPが残りわずかの時も画面の下で知らせる。",
      ],
    },
    {
      title: "遊び方 5/5：拠点の設備",
      lines: [
        "▣ 収納箱：持って行く道具を選ぶ。　図 図鑑：出会ったモンスターを調べる。",
        "碑 記録の石碑：記録を3つまで刻む・読み込む、最初から始める、別のPC用の「記録の呪文」。",
        "案 案内板：この説明をもう一度読める。さあ、門から出発しよう！",
      ],
    },
  ],

  // page 番目のページを開く
  open: function (page) {
    var self = this;
    var n = this.pages.length;
    var pg = this.pages[page];
    var options = [];
    if (page < n - 1) options.push({ label: "次へ", onChoose: function () { self.open(page + 1); } });
    if (page > 0) options.push({ label: "前へ", onChoose: function () { self.open(page - 1); } });
    options.push({ label: page < n - 1 ? "閉じる" : "閉じて始める" });
    Game.dialog.open({ title: pg.title, lines: pg.lines, options: options });
  },

  // 初めて遊ぶ時：説明を読むかたずねる
  askFirstTime: function () {
    var self = this;
    Game.dialog.open({
      title: "ようこそ！",
      lines: [
        "はじめまして。遊び方の説明（短め・5ページ）を読みますか？",
        "あとからでも、拠点の家の左下にある案内板（案）で読めます。",
      ],
      options: [
        { label: "説明を読む", onChoose: function () { self.open(0); } },
        { label: "読まずに始める" },
      ],
    });
  },
};
